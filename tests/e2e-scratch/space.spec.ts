import { test, expect } from '@playwright/test';
test('typing spaces', async ({ page }) => {
	page.on('console', (m) => console.log('CONSOLE', m.type(), m.text()));
	await page.goto('/login');
	await expect(page.getByRole('button', { name: 'Sign in', exact: true })).toBeEnabled();
	await page.getByLabel('Email', { exact: true }).fill(process.env.SCRATCH_EMAIL!);
	await page.getByLabel(/Password/).first().fill('Capstone2026!');
	await page.getByRole('button', { name: 'Sign in', exact: true }).click();
	await expect(page).toHaveURL(/\/app\/tickets/);
	await page.goto('/app/tickets/new');
	await expect(page.locator('.app-shell')).toHaveAttribute('data-hydrated', 'true');
	const box = page.getByRole('textbox', { name: 'Description' });
	await box.click();
	await page.keyboard.type('hello world again', { delay: 120 });
	await page.waitForTimeout(800);
	console.log('DESCRIPTION TEXT', JSON.stringify(await box.textContent()));
	const firstRow = page.locator('a[href^="/app/tickets/"]').filter({ hasNotText: 'New' }).first();
	await page.goto('/app/tickets');
	await page.locator('.rows a').first().click();
	await expect(page.locator('.app-shell')).toHaveAttribute('data-hydrated', 'true');
	const reply = page.getByRole('textbox', { name: 'Comment' });
	await reply.click();
	await page.keyboard.type('reply with spaces', { delay: 120 });
	await page.waitForTimeout(800);
	console.log('REPLY TEXT', JSON.stringify(await reply.textContent()));
	void firstRow;
});
